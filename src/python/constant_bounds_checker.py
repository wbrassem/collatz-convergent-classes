print(" n |      S_n        | D_n |    C_n = S_n / 2^D_n")
print("--------------------------------------------------")

C_max = 0.0

for n in range(1, 51):
    S_n = A186009[n-1]
    D_n = A020914[n-1] - n      # since A020914(n) = n + D_n
    C_n = S_n / (2 ** D_n)
    C_max = max(C_max, C_n)

    print(f"{n:2d} | {S_n:14d} | {D_n:3d} | {C_n:.6f}")

print("\nMaximum C_n over first 50 terms:", C_max)
